def _chain(tmp_path: Path, record: dict[str, Any]) -> bool:
    log = tmp_path / "audit.jsonl"
    log.write_bytes(json.dumps(record, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode() + b"\n")
    return verify_chain(log).ok


def test_b13_1_good_v1_audit_example_passes_the_verifier_and_bad_ones_fail(tmp_path: Path) -> None:
    assert _chain(tmp_path, load(EXAMPLES / "audit-record.good-v1.json"))
    for path in examples("audit-record", "bad"):
        assert not _chain(tmp_path, load(path)), path.name
    # B-17 landed (W2 integration): the v1-then-v2 verifier accepts the v2 example.
    assert _chain(tmp_path, load(EXAMPLES / "audit-record.good-v2.json"))


def test_b13_1_finding_schema_matches_the_tenantbaseline_class() -> None:
    source = (REPO / "levers" / "powershell" / "TenantBaseline" / "TenantBaseline.psm1").read_text(encoding="utf-8")
    block = source.split("class TenantBaselineFinding {", 1)[1].split("TenantBaselineFinding(", 1)[0]
    props = re.findall(r"\[string\]\s+\$(\w+)", block)
    assert props, "could not read the class properties"
    finding = schema("finding")
    assert sorted(props) == sorted(finding["properties"]) == sorted(finding["required"])
    severities = re.search(r"\[ValidateSet\(([^)]*)\)\]\s*\[string\]\s*\$Severity", block)
    assert severities is not None
    assert re.findall(r"'(\w+)'", severities.group(1)) == finding["properties"]["Severity"]["enum"]


def test_b13_1_hand_written_patterns_match_the_python_constraints() -> None:
    proposal = schema("proposal")["properties"]
    lever_pattern, client_pattern = proposal["lever"]["pattern"], proposal["client"]["pattern"]
    request = schema("lever-request")
    assert request["$defs"]["LeverName"]["pattern"] == lever_pattern
    assert request["$defs"]["ClientId"]["pattern"] == client_pattern
    assert request["properties"]["mode"]["enum"] == list(get_args(Mode))
    client = schema("client")
    assert client["$defs"]["DottedName"]["pattern"] == lever_pattern
    assert client["properties"]["id"]["pattern"] == client_pattern
    assert client["$defs"]["CredentialRef"] == request["$defs"]["CredentialRef"]


def test_b13_1_client_schema_holds_only_credential_names_and_no_silent_model_default() -> None:
    client = schema("client")
    assert "default" not in client["properties"]["model_processing"]
    assert "model_processing" in client["required"]
    ref = re.compile(client["$defs"]["CredentialRef"]["pattern"])
    assert ref.search("client-fabrikam-capital-graph")
    # Secret-looking values, built at runtime so no secret pattern sits in the source.
    for value in ("sk-" + "a1" * 24, "eyJ" + "x" * 40 + "." + "y" * 20, "Pass" + "word=" + "z" * 12, "a" * 64):
        assert not ref.search(value), value
    for binding in ("Binding", "M365Binding"):
        assert client["$defs"][binding]["additionalProperties"] is False


