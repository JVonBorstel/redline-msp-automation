REPO = Path(__file__).resolve().parents[3]
SCHEMAS = REPO / "schemas"
EXAMPLES = SCHEMAS / "examples"
NINE = (
    "audit-record",
    "change",
    "client",
    "finding",
    "identities",
    "lever-registry",
    "lever-request",
    "lever-result",
    "proposal",
)
DRAFT = "https://json-schema.org/draft/2020-12/schema"
PWSH = shutil.which("pwsh")
needs_pwsh = pytest.mark.skipif(PWSH is None, reason="pwsh (PowerShell 7.4+) is not installed")


def _load_gen() -> ModuleType:
    spec = importlib.util.spec_from_file_location("gen_schemas", REPO / "tools" / "gen_schemas.py")
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


gen = _load_gen()


def schema(name: str) -> dict[str, Any]:
    data: dict[str, Any] = json.loads((SCHEMAS / f"{name}.schema.json").read_text(encoding="utf-8"))
    return data


def examples(name: str, kind: str) -> list[Path]:
    pattern = f"{name}.good*.json" if kind == "good" else f"{name}.bad-*.json"
    return sorted(EXAMPLES.glob(pattern))


def load(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def model_for(name: str) -> type[BaseModel]:
    model: type[BaseModel] = gen.GENERATED[name][1]()
    return model


def copy_schemas(tmp_path: Path) -> Path:
    target = tmp_path / "schemas"
    shutil.copytree(SCHEMAS, target)
    return target


