"""B-13 schemas/ folder, generator and cross-language drift check.

Acceptance ids B13-1 to B13-3 are defined in specs/B-13.md. Offline and deterministic: the generator runs
in-process or against a copy of schemas/ under tmp_path; committed files are never modified. The B13-3 tests
call PowerShell (`pwsh`) on local files only and skip when it is not installed.
Run: uv run --frozen pytest -p no:cacheprovider tests/py/contract
"""

