def test_b13_1_generator_is_deterministic_and_matches_the_models() -> None:
    first, second = gen.generate(), gen.generate()
    assert first == second
    sources = {"identities": _IdentityFile, "change": Change, "lever-result": InvokeResult, "proposal": Proposal}
    for name, model in sources.items():
        body = json.loads(first[f"{name}.schema.json"])
        assert body["properties"] == model.model_json_schema()["properties"]
    registry = json.loads(first["lever-registry.schema.json"])
    assert registry["properties"]["levers"]["items"] == {"$ref": "#/$defs/LeverDef"}
    assert registry["properties"]["version"] == {"maximum": 1, "minimum": 1, "title": "Version", "type": "integer"}


def test_b13_1_generator_never_writes_a_hand_written_schema(tmp_path: Path) -> None:
    empty = tmp_path / "fresh"
    assert gen.main(["--out", str(empty)]) == 0
    assert sorted(p.name for p in empty.glob("*.schema.json")) == sorted(f"{n}.schema.json" for n in gen.GENERATED)

    folder = copy_schemas(tmp_path)
    before = {n: (folder / f"{n}.schema.json").read_bytes() for n in gen.HAND_WRITTEN}
    (folder / "client.schema.json").write_text('{"hand": "edited"}\n', encoding="utf-8")
    before["client"] = (folder / "client.schema.json").read_bytes()
    assert gen.write(folder) == []  # the committed generated files are already current
    assert {n: (folder / f"{n}.schema.json").read_bytes() for n in gen.HAND_WRITTEN} == before


