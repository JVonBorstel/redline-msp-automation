def test_b13_1_five_are_generated_from_pydantic_and_four_are_hand_written() -> None:
    assert set(gen.GENERATED) == {"lever-registry", "identities", "change", "lever-result", "proposal"}
    assert set(gen.HAND_WRITTEN) == {"lever-request", "audit-record", "finding", "client"}
