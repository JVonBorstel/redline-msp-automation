_PS_VALIDATE = r"""
param([string] $Manifest)
$ErrorActionPreference = 'Stop'
$out = foreach ($item in (Get-Content -LiteralPath $Manifest -Raw | ConvertFrom-Json)) {
    $errs = $null
    $json = Get-Content -LiteralPath $item.doc -Raw -Encoding utf8
    $ok = Test-Json -Json $json -SchemaFile $item.schema -ErrorAction SilentlyContinue -ErrorVariable errs
    [pscustomobject]@{ label = $item.label; ok = [bool] $ok }
}
ConvertTo-Json -InputObject @($out) -Compress
"""


def _test_json(tmp_path: Path, docs: list[tuple[str, str, Any]]) -> dict[str, bool]:
    """Run PowerShell Test-Json -SchemaFile on each (label, schema name, document); label -> accepted."""
    manifest = []
    for index, (label, name, doc) in enumerate(docs):
        path = tmp_path / f"doc-{index}.json"
        path.write_text(json.dumps(doc), encoding="utf-8")
        manifest.append({"label": label, "schema": str(SCHEMAS / f"{name}.schema.json"), "doc": str(path)})
    (tmp_path / "manifest.json").write_text(json.dumps(manifest), encoding="utf-8")
    (tmp_path / "validate.ps1").write_text(_PS_VALIDATE, encoding="utf-8")
    assert PWSH is not None
    proc = subprocess.run(  # noqa: S603
        [PWSH, "-NoProfile", "-File", str(tmp_path / "validate.ps1"), "-Manifest", str(tmp_path / "manifest.json")],
        capture_output=True,
        text=True,
        check=False,
        timeout=120,
    )
    assert proc.returncode == 0, proc.stderr
    return {row["label"]: row["ok"] for row in json.loads(proc.stdout)}


@needs_pwsh
def test_b13_3_real_python_output_passes_test_json_and_a_tampered_copy_does_not(tmp_path: Path) -> None:
    tenant_dir = tmp_path / "tenant"
    shutil.copytree(DEFAULT_TENANT_DIR, tenant_dir)
    audit_path = tmp_path / "audit.jsonl"
    runner = LeverRunner(Registry.load(), IdentityStore.load(), MockTenant(tenant_dir), AuditLog(audit_path))
    params = {"upn": "jamie.chen@contosodental.example", "reason": "Left the practice (ticket T-1002)"}
    result = runner.invoke("user.disable", params, "triage-bot", "contoso-dental", mode="dry-run")
    denied = runner.invoke("user.disable", params, "tech-ben", "contoso-dental", mode="dry-run")
    assert result.ok and result.diff and denied.status == "denied"
    records = [json.loads(line) for line in audit_path.read_text(encoding="utf-8").splitlines()]
    proposal = Proposal.new(
        source="triage",
        ref="T-1002",
        lever="user.disable",
        client="contoso-dental",
        params=params,
        requested_by="triage-bot",
        reason="Left the practice; disable after a lead approves.",
    )
    tampered = {**result.model_dump(mode="json"), "shell": "Invoke-Expression"}
    docs: list[tuple[str, str, Any]] = [
        ("result", "lever-result", result.model_dump(mode="json")),
        ("denied", "lever-result", denied.model_dump(mode="json")),
        ("change", "change", result.diff[0].model_dump(mode="json")),
        ("proposal", "proposal", proposal.model_dump(mode="json")),
        ("audit-1", "audit-record", records[0]),
        ("audit-2", "audit-record", records[1]),
        ("tampered-result", "lever-result", tampered),
        ("tampered-audit", "audit-record", {**records[0], "mode": "delete"}),
    ]
    accepted = _test_json(tmp_path, docs)
    assert accepted == {label: not label.startswith("tampered") for label, _, _ in docs}


