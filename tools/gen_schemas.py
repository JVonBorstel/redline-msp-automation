"""Write the pydantic-sourced JSON Schemas in schemas/ (B-13, STD-XL-2).

The pydantic models are the source of truth. This script turns five of them into draft 2020-12 JSON
Schema files that PowerShell checks with `Test-Json -SchemaFile`. The other four schemas in
schemas/ have no pydantic model yet and are written by hand; this script never touches them.

    uv run --frozen python tools/gen_schemas.py            # rewrite the generated files
    uv run --frozen python tools/gen_schemas.py --check    # write nothing; exit 1 on any drift
    uv run --frozen python tools/gen_schemas.py --out DIR  # write (or --check) another folder

Exit codes: 0 in sync (or written), 1 drift found, 2 usage error.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Callable
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parents[1]
if str(REPO) not in sys.path:
    sys.path.insert(0, str(REPO))

from pydantic import BaseModel, create_model  # noqa: E402

from core.identity.store import _IdentityFile  # noqa: E402
from core.levers.models import Change, InvokeResult, LeverDef  # noqa: E402
from core.levers.registry import _RegistryFile  # noqa: E402
from core.queue.store import Proposal  # noqa: E402

SCHEMA_DIR = REPO / "schemas"
DRAFT = "https://json-schema.org/draft/2020-12/schema"
ID_BASE = "https://redline-msp-automation.example/schemas/"

# Schemas with no pydantic model yet (STD-XL-1 "new", or a shape that starts in PowerShell).
HAND_WRITTEN: tuple[str, ...] = ("lever-request", "audit-record", "finding", "client")


def _registry_model() -> type[BaseModel]:
    # The loader reads `levers` as raw dicts and validates each with LeverDef, so the file's shape is
    # _RegistryFile with that list typed. Subclassing keeps _RegistryFile's config and version rule.
    model: type[BaseModel] = create_model("LeverRegistryFile", __base__=_RegistryFile, levers=(list[LeverDef], ...))
    return model


# name -> (source label for $comment, model factory)
GENERATED: dict[str, tuple[str, Callable[[], type[BaseModel]]]] = {
    "lever-registry": (
        "core.levers.registry._RegistryFile with levers: list[core.levers.models.LeverDef]",
        _registry_model,
    ),
    "identities": ("core.identity.store._IdentityFile", lambda: _IdentityFile),
    "change": ("core.levers.models.Change", lambda: Change),
    "lever-result": ("core.levers.models.InvokeResult", lambda: InvokeResult),
    "proposal": ("core.queue.store.Proposal", lambda: Proposal),
}

ALL_SCHEMAS: tuple[str, ...] = tuple(sorted((*GENERATED, *HAND_WRITTEN)))


def file_name(name: str) -> str:
    return f"{name}.schema.json"


def build(name: str) -> dict[str, Any]:
    """The schema document for one generated name, with the draft, id and source in front."""
    source, factory = GENERATED[name]
    body = factory().model_json_schema(by_alias=True, mode="validation")
    head: dict[str, Any] = {
        "$schema": DRAFT,
        "$id": ID_BASE + file_name(name),
        "$comment": f"Generated by tools/gen_schemas.py from {source}. Do not edit by hand; run the script.",
    }
    return {**head, **body}


def render(schema: dict[str, Any]) -> str:
    return json.dumps(schema, indent=2, ensure_ascii=False) + "\n"


def generate() -> dict[str, str]:
    """File name -> exact text for every generated schema."""
    return {file_name(name): render(build(name)) for name in GENERATED}


def _normalise(text: str) -> str:
    return text.replace("\r\n", "\n")


def check(folder: Path) -> list[str]:
    """Problems with `folder`: generated files that differ or are missing, and unexpected schema files."""
    problems: list[str] = []
    for fname, want in generate().items():
        path = folder / fname
        if not path.is_file():
            problems.append(f"{fname}: missing (run tools/gen_schemas.py)")
        elif _normalise(path.read_text(encoding="utf-8")) != want:
            problems.append(f"{fname}: differs from the pydantic model (run tools/gen_schemas.py)")
    for name in HAND_WRITTEN:
        if not (folder / file_name(name)).is_file():
            problems.append(f"{file_name(name)}: missing (hand-written; restore it)")
    known = {file_name(name) for name in ALL_SCHEMAS}
    for path in sorted(folder.glob("*.schema.json")):
        if path.name not in known:
            problems.append(f"{path.name}: not a known schema (add it to tools/gen_schemas.py or remove it)")
    return problems


def write(folder: Path) -> list[str]:
    """Write every generated schema that differs; return the names written."""
    folder.mkdir(parents=True, exist_ok=True)
    written: list[str] = []
    for fname, text in generate().items():
        path = folder / fname
        if path.is_file() and _normalise(path.read_text(encoding="utf-8")) == text:
            continue
        with path.open("w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        written.append(fname)
    return written


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate the pydantic-sourced JSON Schemas in schemas/.")
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 if any schema is out of date")
    parser.add_argument("--out", type=Path, default=SCHEMA_DIR, help="schema folder (default: schemas/)")
    args = parser.parse_args(argv)
    folder: Path = args.out
    if args.check:
        problems = check(folder)
        for line in problems:
            print(f"DRIFT {line}")
        print(f"schemas: {len(ALL_SCHEMAS)} expected, {len(problems)} problem(s) in {folder}")
        return 1 if problems else 0
    for fname in write(folder):
        print(f"wrote {fname}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
