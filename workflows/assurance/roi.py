"""ROI tracker rows (B-95, B95-2): acceptance rates read from this repo's eval reports, every row
labelled fixture-based.

A row names a committed report and one line of it (the anchor) that must appear verbatim; the row's two counts must be
numbers in that line. So a regenerated report with other numbers fails ``check_roi`` until the row is updated.
Minutes per run, runs per month and build effort are invented placeholders and are marked (assumed) wherever they
are shown.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, ValidationError, model_validator

from core.paths import REPO_ROOT
from workflows.assurance.rubric import RiskClass, Rubric, monthly_hours, priority

ROI_PATH = REPO_ROOT / "governance" / "roi_fixtures.json"
ROW_ID = r"^[a-z][a-z0-9-]{1,40}$"
HEADER = (
    "# ROI tracker",
    "",
    "Status: **built** (generator, checker and tests; the numbers are fixture-based)",
    "",
)


class RoiError(ValueError):
    """The ROI fixture file is missing or invalid."""


class RoiRow(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)

    id: str = Field(pattern=ROW_ID)
    basis: Literal["fixture-based"]
    automation: str = Field(min_length=1, max_length=120)
    inventory_id: str = Field(pattern=r"^W-[A-Z0-9]+-\d{2}$")
    report: str = Field(min_length=1)
    anchor: str = Field(min_length=1)
    metric: str = Field(min_length=1, max_length=160)
    numerator: int = Field(ge=0)
    denominator: int = Field(gt=0)
    risk_class: RiskClass
    minutes_per_run: float = Field(gt=0)
    runs_per_month: int = Field(ge=1)
    effort_days: float = Field(gt=0)

    @model_validator(mode="after")
    def _counts_are_consistent(self) -> RoiRow:
        if self.numerator > self.denominator:
            raise ValueError(f"{self.id}: numerator {self.numerator} is more than denominator {self.denominator}")
        return self

    @property
    def acceptance(self) -> float:
        return self.numerator / self.denominator

    @property
    def hours(self) -> float:
        return monthly_hours(self.minutes_per_run, self.runs_per_month)


def load_roi(path: Path = ROI_PATH) -> list[RoiRow]:
    try:
        raw = json.loads(Path(path).read_text(encoding="utf-8"))
        basis = raw["basis"]
        return [RoiRow.model_validate({**row, "basis": basis}) for row in raw["rows"]]
    except (OSError, ValueError, KeyError, TypeError, ValidationError) as exc:
        raise RoiError(f"cannot load ROI fixtures {path}: {exc}") from exc


def check_roi(rows: list[RoiRow], root: Path = REPO_ROOT) -> list[str]:
    """Problems found, one per line; empty when every row is backed by its report."""
    problems: list[str] = []
    seen: set[str] = set()
    for row in rows:
        if row.id in seen:
            problems.append(f"{row.id}: duplicate row id")
        seen.add(row.id)
        report = (root / row.report).resolve()
        if not report.is_relative_to(root.resolve()) or not report.is_file():
            problems.append(f"{row.id}: report {row.report} does not exist")
            continue
        if row.anchor not in report.read_text(encoding="utf-8"):
            problems.append(f"{row.id}: anchor line is not in {row.report}: {row.anchor!r}")
            continue
        for count in (row.numerator, row.denominator):
            if not re.search(rf"(?<![\d.]){count}(?![\d.])", row.anchor):
                problems.append(f"{row.id}: count {count} is not a number in its anchor line")
    return problems


def render_roi(rows: list[RoiRow], rubric: Rubric) -> str:
    weights = rubric.risk_weights
    lines = list(HEADER)
    lines += [
        "> Independently built prototype. Not affiliated with any vendor's or real company's systems. Synthetic data "
        "only.",
        "",
        "This page is generated by `uv run --frozen python -m workflows.assurance generate --write` from "
        "`governance/roi_fixtures.json`, `governance/intake_rubric.json` and the committed eval reports. Do not edit "
        "it by "
        "hand; `check` fails when it drifts.",
        "",
        "**Every number below is fixture-based.** The acceptance column is a count read from an eval report whose "
        "gold labels, fixtures and rules were written by one author, with mock providers. Minutes per run, runs per "
        "month "
        "and build effort are invented placeholders (assumed), not the MSP figures. **Not a saving**: the hours column "
        "is "
        "assumed hours multiplied by a fixture rate; it shows the method, not money or time saved at any client.",
        "",
        "## Method",
        "",
        "`priority = (assumed hours per month x fixture acceptance) / (assumed effort in days x risk weight)`, rounded "
        "to "
        "two places. Hours per month = assumed minutes per run x assumed runs per month / 60. Risk weight by class: "
        + ", ".join(f"{k} = {v}" for k, v in sorted(weights.items()))
        + " (proposals; `governance/intake_rubric.json`). The same function scores an intake "
        "(`governance/USE_CASE_INTAKE.md`).",
        "",
        "## Rows",
        "",
        "| Automation | Minutes per run (assumed) | Runs per month (assumed) | Hours per month (assumed) | "
        "Acceptance (fixture) | What was counted | Risk class | Effort days (assumed) | Priority | Basis | Source |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    ordered = sorted(
        rows,
        key=lambda r: (
            -priority(hours=r.hours, acceptance=r.acceptance, effort_days=r.effort_days, weight=weights[r.risk_class]),
            r.id,
        ),
    )
    for r in ordered:
        score = priority(
            hours=r.hours, acceptance=r.acceptance, effort_days=r.effort_days, weight=weights[r.risk_class]
        )
        lines.append(
            f"| {r.automation} | {r.minutes_per_run:g} | {r.runs_per_month} | {r.hours:.2f} | "
            f"{r.numerator}/{r.denominator} = {r.acceptance * 100:.1f}% | {r.metric} | {r.risk_class} | "
            f"{r.effort_days:g} | {score:.2f} | fixture-based | `{r.report}` |"
        )
    lines += [
        "",
        "## Limits",
        "",
        "- Acceptance here is the share of fixture cases an automation got right against author-written gold labels. "
        "It is "
        "not the share of drafts a technician would accept unedited; no technician has used any of these.",
        "- Every automation in the table is read-only or draft-only (R0), so the risk weight does not separate them.",
        "- Rows are ranked by the formula only; nothing about build order, staffing or value to a real client follows.",
        "- Replace the assumed columns with the MSP's own measurements before showing any figure as a result.",
        "",
    ]
    return "\n".join(lines)
