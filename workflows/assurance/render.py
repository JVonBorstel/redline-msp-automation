def score_examples(root: Path = REPO_ROOT) -> list[Scored]:
    rubric = load_rubric(root / "governance" / "intake_rubric.json")
    roi = {row.id: row for row in load_roi(root / "governance" / "roi_fixtures.json")}
    never = NeverAutomate.load(root / "governance" / "never-automate.json")
    return [score(i, rubric=rubric, roi=roi, never=never) for i in load_intakes(root / INTAKE_DIR)]


def ordered(scored: list[Scored]) -> list[Scored]:
    """Ranked ideas first (highest priority first), then the rest by id."""
    ranked = rank(scored)
    ids = {s.id for s in ranked}
    return ranked + sorted((s for s in scored if s.id not in ids), key=lambda s: s.id)


def _allowed(prop: dict[str, Any]) -> str:
    if "enum" in prop:
        return ", ".join(f"`{v}`" for v in prop["enum"])
    if "const" in prop:
        return f"`{prop['const']}`"
    options = prop.get("anyOf")
    if options:
        return " or ".join(_allowed(o) for o in options)
    if prop.get("type") == "null":
        return "null"
    if prop.get("type") == "array":
        item = _allowed(prop.get("items", {}))
        return f"list of {item}" if item else "list"
    bits: list[str] = []
    for key, label in (
        ("pattern", "pattern"),
        ("minLength", "min length"),
        ("maxLength", "max length"),
        ("exclusiveMinimum", "more than"),
        ("minimum", "at least"),
        ("maximum", "at most"),
    ):
        if key in prop:
            bits.append(f"{label} `{prop[key]}`" if key == "pattern" else f"{label} {prop[key]}")
    head = str(prop.get("type", ""))
    return (head + (": " if bits and head else "") + ", ".join(bits)).strip()


