def generate_all(root: Path = REPO_ROOT) -> dict[str, str]:
    rubric = load_rubric(root / "governance" / "intake_rubric.json")
    rows: list[RoiRow] = load_roi(root / "governance" / "roi_fixtures.json")
    return {
        OUT_INTAKE: render_intake_doc(root),
        OUT_ROI: render_roi(rows, rubric),
        OUT_SOC2: render_mapping(load_controls(root), load_mapping(root)),
        OUT_RISK: render_register(root),
        OUT_SCHEMA: json.dumps(UseCaseIntake.model_json_schema(), indent=2) + "\n",
    }


def drift(root: Path, outputs: dict[str, str]) -> list[str]:
    """Files that are missing or differ from the generated text."""
    problems: list[str] = []
    for rel, text in sorted(outputs.items()):
        path = root / rel
        if not path.is_file():
            problems.append(f"{rel}: missing; run generate --write")
        elif path.read_text(encoding="utf-8") != text:
            problems.append(f"{rel}: differs from the generated text; run generate --write")
    return problems


def check_all(root: Path = REPO_ROOT) -> list[str]:
    """Every B-95 check in one list: ROI backing, mapping backing, register, intakes, and generated-file drift."""
    problems: list[str] = []
    rows = load_roi(root / "governance" / "roi_fixtures.json")
    problems += check_roi(rows, root)
    controls = load_controls(root)
    problems += check_mapping(load_mapping(root), controls, root)
    air = parse_air_table((root / GOVERNANCE_MAP).read_text(encoding="utf-8"))
    problems += check_register(load_register(root), air, controls)
    score_examples(root)  # raises IntakeError naming the file when an example is invalid
    problems += drift(root, generate_all(root))
    return problems
